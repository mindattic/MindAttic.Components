using System.Collections;
using System.Text.Json.Nodes;
using System.Windows;
using System.Windows.Automation;
using System.Windows.Controls;
using System.Windows.Media;

namespace MindAttic.Components.Wpf.Controls;

/// <summary>
/// A settings editor generated at runtime from a settings manifest (M.COMP-T159), so one app (Vault.Desktop) can edit
/// any app's settings with no app UI code. <see cref="Load"/> takes the manifest (the camelCase JSON MindAttic.Vault's
/// SettingsManifestBuilder writes: <c>fields</c> of <c>{ name, property, label, group, help, order, kind, readOnly,
/// nullable, default, min, max, choices, pathKind, pathFilter, fields, itemLabel, itemName, itemDefault }</c>) and the
/// app's settings document, and renders one full-width <see cref="MaSettingRow"/> per field, grouped under group
/// headings and sorted by order. Editing changes the document in place and raises <see cref="FieldChanged"/> with the
/// field's full name; a missing property shows the field's default until edited. Objects nest, collections of objects
/// get Add / Remove / Edit with each item's rows generated by the same code, and an unknown kind renders read-only.
/// Each kind's editor comes from <see cref="Editors"/>, which a host can extend.
/// </summary>
public class MaSettingsForm : FrameworkElement
{
    private readonly ScrollViewer _scroll;
    private readonly StackPanel _panel = new();

    /// <summary>An empty form; call <see cref="Load"/>.</summary>
    public MaSettingsForm()
    {
        _scroll = new ScrollViewer { Content = _panel, VerticalScrollBarVisibility = ScrollBarVisibility.Auto, HorizontalScrollBarVisibility = ScrollBarVisibility.Disabled };
        _scroll.SetResourceReference(StyleProperty, "MaBodyScroll");
        AddVisualChild(_scroll);
        AddLogicalChild(_scroll);
        AutomationProperties.SetName(this, "Settings");
    }

    /// <summary>Raised after the user changes a field (never during <see cref="Load"/>).</summary>
    public event EventHandler<MaFieldChangedEventArgs>? FieldChanged;

    /// <summary>The editor for each kind; register a kind of your own before <see cref="Load"/>.</summary>
    public MaFieldEditorRegistry Editors { get; } = MaFieldEditorRegistry.CreateDefault();

    /// <summary>The loaded manifest.</summary>
    public JsonObject? Manifest { get; private set; }

    /// <summary>The settings document being edited in place.</summary>
    public JsonObject? Document { get; private set; }

    /// <summary>How long <see cref="ScrollTo"/> lights the row (2 s).</summary>
    public TimeSpan HighlightDuration { get; set; } = TimeSpan.FromSeconds(2);

    /// <summary>Answers a Path field's Browse button with the chosen path, or null when cancelled. Null (the default)
    /// shows the Windows file or folder dialog.</summary>
    public Func<MaPathRequest, string?>? PathPicker { get; set; }

    /// <summary>The scroll viewer the rows sit in.</summary>
    public ScrollViewer ScrollViewer => _scroll;

    /// <summary>Every row built so far, nested ones included (a collection item's rows exist once it was opened).</summary>
    public IEnumerable<MaSettingRow> Rows => Descendants<MaSettingRow>(_panel);

    /// <summary>Renders <paramref name="manifest"/>'s fields editing <paramref name="document"/>.</summary>
    public void Load(JsonObject manifest, JsonObject document)
    {
        Manifest = manifest ?? throw new ArgumentNullException(nameof(manifest));
        Document = document ?? throw new ArgumentNullException(nameof(document));
        _panel.Children.Clear();
        var prefix = ManifestJson.Str(manifest, "configurationPrefix") ?? "";
        _panel.Children.Add(BuildRows(ManifestJson.Fields(manifest), _ => document, prefix, prefix, nested: false));
    }

    /// <summary>The row for a full name (case-insensitive), or null when it isn't built.</summary>
    public MaSettingRow? FindRow(string fieldName) =>
        Rows.FirstOrDefault(r => string.Equals(r.FieldName, fieldName, StringComparison.OrdinalIgnoreCase));

    /// <summary>Scrolls the row for <paramref name="fieldName"/> into view and lights it for
    /// <see cref="HighlightDuration"/>, opening the collection item it's in. A name with <c>*</c> for an item index, or
    /// an item that no longer exists, goes to the collection's row. False when there's no such field.</summary>
    public bool ScrollTo(string fieldName)
    {
        if (string.IsNullOrWhiteSpace(fieldName)) return false;
        var row = FindRow(fieldName);
        for (var guard = 0; row is null && guard < 16; guard++)
        {
            var opened = false;
            foreach (var collection in Descendants<CollectionEditor>(_panel).ToList())
                if (collection.TryOpenItemFor(fieldName))
                {
                    opened = true;
                    break;
                }
            if (!opened) break;
            row = FindRow(fieldName);
        }
        row ??= NearestCollectionRow(fieldName);
        if (row is null) return false;

        CollectionEditor.CollectionItemCard.OpenAround(row);
        UpdateLayout();
        row.BringIntoView();
        row.Highlight(HighlightDuration);
        return true;
    }

    private MaSettingRow? NearestCollectionRow(string fieldName) =>
        Rows.Where(r => r.Context.Kind.Equals(MaFieldKinds.Collection, StringComparison.OrdinalIgnoreCase)
                        && (fieldName.StartsWith(r.FieldName + ":", StringComparison.OrdinalIgnoreCase)
                            || fieldName.StartsWith(r.Context.ManifestName + ":", StringComparison.OrdinalIgnoreCase)))
            .OrderByDescending(r => r.FieldName.Length)
            .FirstOrDefault();

    /// <summary>Checks every built row (ranges, URLs, numbers that don't parse, duplicate keys) and, when
    /// <paramref name="show"/>, shows each error on its row and clears the rest.</summary>
    public IReadOnlyList<MaSettingError> Validate(bool show = true)
    {
        var errors = new List<MaSettingError>();
        foreach (var row in Rows)
        {
            string? message;
            try { message = row.Context.Validator?.Invoke(); }
            catch (Exception ex) { message = ex.Message; }
            if (message is not null) errors.Add(new MaSettingError(row.FieldName, message));
            if (show) row.Error = message;
        }
        return errors;
    }

    /// <summary>Hides every row's error.</summary>
    public void ClearErrors()
    {
        foreach (var row in Rows) row.Error = null;
    }

    internal void RaiseFieldChanged(string fieldName)
    {
        foreach (var collection in Descendants<CollectionEditor>(_panel)) collection.OnFieldChanged(fieldName);
        FieldChanged?.Invoke(this, new MaFieldChangedEventArgs(fieldName));
    }

    internal FrameworkElement BuildRows(IEnumerable<JsonObject> fields, Func<bool, JsonObject?> parent, string manifestPrefix, string namePrefix, bool nested)
    {
        var panel = new StackPanel();
        var sorted = fields.Select((f, i) => (Field: f, Index: i))
            .OrderBy(x => ManifestJson.Order(x.Field)).ThenBy(x => x.Index)
            .Select(x => x.Field).ToList();
        var groups = sorted.GroupBy(f => ManifestJson.Str(f, "group") is { Length: > 0 } g ? g : "General").ToList();
        foreach (var group in groups)
        {
            if (!nested || groups.Count > 1)
            {
                var heading = new TextBlock { Text = group.Key.ToUpperInvariant() };
                heading.SetResourceReference(StyleProperty, "MaSectionLabel");
                AutomationProperties.SetName(heading, group.Key);
                panel.Children.Add(heading);
            }
            foreach (var field in group)
                panel.Children.Add(BuildRow(field, parent, manifestPrefix, namePrefix));
        }
        return panel;
    }

    private MaSettingRow BuildRow(JsonObject field, Func<bool, JsonObject?> parent, string manifestPrefix, string namePrefix)
    {
        var property = ManifestJson.Str(field, "property") ?? "";
        var name = ManifestJson.Str(field, "name") is { Length: > 0 } n
            ? n.StartsWith(manifestPrefix + ":", StringComparison.Ordinal) ? namePrefix + n[manifestPrefix.Length..] : n
            : namePrefix.Length > 0 ? namePrefix + ":" + property : property;
        var context = new MaFieldContext(this, field, name, parent);

        FrameworkElement editor;
        try
        {
            editor = string.IsNullOrEmpty(property)
                ? MaFieldEditors.ReadOnly(context)
                : Editors.TryGet(context.Kind, out var factory) ? factory(context) : MaFieldEditors.ReadOnly(context);
        }
        catch (Exception ex) when (ex is not OutOfMemoryException)
        {
            context.Validator = null;
            editor = MaFieldEditors.ReadOnly(context);
        }
        if (context.ReadOnly)
        {
            if (editor is TextBox box) box.IsReadOnly = true;
            else editor.IsEnabled = false;
        }
        var row = new MaSettingRow(context, editor);
        context.Row = row;
        return row;
    }

    internal static IEnumerable<T> Descendants<T>(DependencyObject root) where T : DependencyObject
    {
        foreach (var child in LogicalTreeHelper.GetChildren(root).OfType<DependencyObject>())
        {
            if (child is T t) yield return t;
            foreach (var d in Descendants<T>(child)) yield return d;
        }
    }

    /// <inheritdoc />
    protected override int VisualChildrenCount => 1;

    /// <inheritdoc />
    protected override Visual GetVisualChild(int index) => index == 0 ? _scroll : throw new ArgumentOutOfRangeException(nameof(index));

    /// <inheritdoc />
    protected override IEnumerator LogicalChildren => new object[] { _scroll }.GetEnumerator();

    /// <inheritdoc />
    protected override Size MeasureOverride(Size availableSize)
    {
        _scroll.Measure(availableSize);
        return _scroll.DesiredSize;
    }

    /// <inheritdoc />
    protected override Size ArrangeOverride(Size finalSize)
    {
        _scroll.Arrange(new Rect(finalSize));
        return finalSize;
    }
}
