// Regenerates tests/baselines.json: the recorded pixel size of every raster asset, plus the SHA-256 of every
// LOSSY file (JPEG). The tests use it as a ratchet:
//   * an image may never get smaller than its baseline (no silent downscaling),
//   * a JPEG may never change bytes (lossy-to-lossy re-encoding degrades quality; assets under an
//     immutable tag are replaced by a NEW file name or a deliberate baseline update, never silently).
//
//   node lib/update-baselines.mjs                 record everything currently in the tree
//   node lib/update-baselines.mjs --from <dir>    also record files from a staging dir laid out as
//                                                 <domain>/[assets/]<category>/<file> (not yet copied in)
//
// Run it deliberately, after adding or replacing an asset, and commit the result with the asset.
import fs from 'node:fs';
import path from 'node:path';
import { SHARED_ROOT, ASSET_ROOTS } from './paths.mjs';
import { listAssets, readAsset, sha256, walk, posix } from './walk.mjs';
import { decodeRaster } from './binfmt.mjs';

const RASTER = new Set(['.png', '.jpg', '.jpeg', '.gif', '.ico']);
const LOSSY = new Set(['.jpg', '.jpeg']);
const out = path.join(SHARED_ROOT, 'tests', 'package', 'baselines.json');
const images = {};

function record(rel, buf) {
  const ext = path.extname(rel).toLowerCase();
  if (!RASTER.has(ext)) return;
  const d = decodeRaster(rel, buf);
  if (!d?.ok) throw new Error(`${rel}: refusing to baseline an undecodable image (${d?.errors?.join('; ')})`);
  images[rel] = { width: d.width, height: d.height, ...(LOSSY.has(ext) ? { sha256: sha256(buf) } : {}) };
}

for (const rel of listAssets()) record(rel, readAsset(rel));

const fromIdx = process.argv.indexOf('--from');
if (fromIdx > -1) {
  const dir = path.resolve(process.argv[fromIdx + 1]);
  for (const abs of walk(dir)) {
    let rel = posix(path.relative(dir, abs));
    rel = rel.replace(/^([^/]+)\/assets\//, '$1/'); // normalise any <domain>/assets/ level to <domain>/ (the package has none)
    if (!ASSET_ROOTS.some((r) => rel.startsWith(r + '/'))) continue;
    if (!(rel in images)) record(rel, fs.readFileSync(abs));
  }
}

const sorted = Object.fromEntries(Object.entries(images).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(out, JSON.stringify({ $comment: 'Generated by tests/lib/update-baselines.mjs. Ratchet for image dimensions and for lossy-file bytes; see tests/README.md.', images: sorted }, null, 2) + '\n');
console.log(`baselines.json: ${Object.keys(sorted).length} images`);
